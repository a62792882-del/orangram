create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null check (username ~ '^[a-z0-9_]{3,24}$'),
  display_name text not null,
  oranges integer not null default 0 check (oranges >= 0),
  created_at timestamptz not null default now()
);
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 4000),
  created_at timestamptz not null default now()
);
create index if not exists messages_sender_recipient_time on public.messages(sender_id,recipient_id,created_at);
create index if not exists messages_recipient_sender_time on public.messages(recipient_id,sender_id,created_at);
alter table public.profiles enable row level security;
alter table public.messages enable row level security;
create policy "Profiles are searchable by signed-in users" on public.profiles for select to authenticated using (true);
create policy "Users can create own profile" on public.profiles for insert to authenticated with check (auth.uid() = id);
create policy "Users can update own profile" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);
create policy "Users can read their messages" on public.messages for select to authenticated using (auth.uid() = sender_id or auth.uid() = recipient_id);
create policy "Users can send as themselves" on public.messages for insert to authenticated with check (auth.uid() = sender_id and sender_id <> recipient_id);
alter publication supabase_realtime add table public.messages;
